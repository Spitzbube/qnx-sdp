/*
	GUID Partition Types

	Sources:
	http://en.wikipedia.org/wiki/GUID_Partition_Table
	http://de.wikipedia.org/wiki/GUID_Partition_Table

	For each known partition type, three macros are defined:
		GPART_GUID_INITIALIZER_<type>
		    The binary partition-type GUID, as a constant initializer
		GPART_GUID_<type>
		    The binary partition-type GUID, as a runtime expression
		GPART_TYPE_<type>
		    A unique [short] alias name for the partition type
		GPART_DESC_<type>
		    A longer description of the partition type
*/

